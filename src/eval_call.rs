// Import eval function and context from eval module
// Note: this creates a circular dependency, but it's safe because
// eval.rs imports invoke_function/CallContext from this module, while
// this module imports eval/EvalContext from eval.rs. Neither module's
// initialization depends on the other.
use crate::eval::{materialize, value_matches_type, EvalContext};
use crate::eval_core::eval_core_expr;

const DEFAULT_ANNOTATION_KEY: &str = "default";

/// Extract a human-readable label from a CoreExpr function position for stack frames.
///
/// Operates on `CoreExpr` directly so `eval_call_core` does not need any
/// conversion solely for the label.
pub(crate) fn func_label_core(expr: &CoreExpr) -> Option<Arc<str>> {
    match expr {
        CoreExpr::Var { name, .. } => Some(Arc::from(name.as_str())),
        CoreExpr::Fn {
            desugared: true, ..
        } => Some(Arc::from("<auto-generated lambda>")),
        _ => None,
    }
}

/// Evaluate a CoreExpr::Call natively — return a PendingCall thunk without round-tripping
/// the function or argument expressions back through `Expr`.
///
/// This is the Parts-B+E migration path for `CoreExpr::Call` in `eval_core_expr`.
/// It mirrors `eval_call` exactly but accepts `Arc<Spanned<CoreExpr>>` slices directly,
/// avoiding the per-argument `core_expr_to_expr` allocation that the old bridge code
/// performed in `eval_core_expr`.
///
/// # Implementation notes
///
/// Arguments use `Thunk::core_expr` (storing `Arc<Spanned<CoreExpr>>` directly)
/// — no per-arg allocation. The function expression is evaluated directly via
/// `eval_core_expr`, avoiding bridge round-trips.
pub(crate) async fn eval_call_core(
    func_expr: &Spanned<CoreExpr>,
    args: &[Arc<Spanned<CoreExpr>>],
    named_args: &[Spanned<CoreNamedArg>],
    caller_env_id: u32,
    ctx: &Arc<EvalContext>,
    call_span: &Span,
    original_call: Arc<Spanned<CoreExpr>>,
    caller_frame: &Arc<EvalFrame>,
) -> EvalResult<Arc<Thunk>> {
    let func_thunk = eval_core_expr(func_expr, caller_frame, ctx).await?;

    // Wrap positional arguments as Unevaluated CoreExpr thunks (Arc<Thunk> directly).
    // Use the caller's EvalFrame so that LetrecGroupMember/ClosureCapture variable
    // references inside argument expressions resolve against the call site's scope.
    let pos_args: Vec<Arc<Thunk>> = args
        .iter()
        .map(|arg| {
            Arc::new(Thunk::core_expr(
                Arc::clone(arg),
                Arc::clone(caller_frame),
                Arc::clone(ctx),
                arg.span.clone(),
            ))
        })
        .collect();

    // Wrap named arguments as Unevaluated CoreExpr thunks (Arc<Thunk> directly).
    let named_args_map = if named_args.is_empty() {
        IndexMap::new()
    } else {
        let mut m = IndexMap::with_capacity(named_args.len());
        for na in named_args {
            let t = Arc::new(Thunk::core_expr(
                Arc::clone(&na.node.value),
                Arc::clone(caller_frame),
                Arc::clone(ctx),
                na.node.value.span.clone(),
            ));
            m.insert(na.node.name.clone(), t);
        }
        m
    };

    // Return PendingCall thunk — function dispatch deferred to PendingCallDispatch in run().
    // Attach the function label (if known) to the call span for blame tracking.
    let thunk_span = if let Some(label) = func_label_core(&func_expr.node) {
        call_span.clone().with_name(label)
    } else {
        call_span.clone()
    };
    Ok(Arc::new(Thunk::fn_call(
        func_thunk,
        pos_args,
        named_args_map,
        thunk_span,
        crate::value::FnCallSpec {
            call_span: call_span.clone(),
            caller_env_id,
            ctx: Arc::clone(ctx),
            original_call,
        },
    )))
}

/// Arguments for invoking a user-defined function.
///
/// `default_env` is the environment used to evaluate default expressions for
/// optional params. For normal calls this is the caller's environment; for
/// `apply` it is the closure environment.
pub struct CallContext<'a> {
    pub params: &'a [Param],
    pub body: &'a Arc<Spanned<CoreExpr>>,
    /// Captured closure environment (replaces closure_env_id u32 + scope_arena lookup).
    pub closure_env: Arc<Vec<Arc<Thunk>>>,
    pub positional: &'a [Arc<Thunk>],
    pub named: Option<&'a IndexMap<String, Arc<Thunk>>>,
    /// Call site span — `name` field carries the function label for blame tracking.
    pub call_span: Span,
    pub ctx: &'a Arc<EvalContext>,
}

/// Invoke a user-defined function with pre-evaluated thunks.
///
/// Binds positional and named args to function params (respecting defaults and
/// variadics), then wraps the body as an unevaluated thunk. This is the shared
/// call path for both `eval_call` and `builtin_apply`.
pub async fn invoke_function(ctx: &CallContext<'_>) -> EvalResult<Arc<Thunk>> {
    // bind_args builds an EvalFrame for the call frame from the bound params.
    let frame = bind_args_thunks(
        ctx.params,
        ctx.positional,
        ctx.named,
        Arc::clone(&ctx.closure_env),
        ctx.ctx,
        &ctx.call_span,
    )
    .await
    .map_err(|mut e| {
        e.set_arity_callee(ctx.call_span.name.clone());
        e
    })?;
    let thunk = Thunk::core_expr(
        Arc::clone(ctx.body),
        frame,
        Arc::clone(ctx.ctx),
        ctx.call_span.clone(),
    );
    Ok(Arc::new(thunk))
}

/// TCO variant of `invoke_function` that returns the body expression and call EvalFrame
/// directly instead of creating a thunk. This allows the caller to reuse the current
/// continuation frame instead of pushing a new Memoize continuation.
///
/// Returns `(body_expr, call_frame)` so the caller can construct `Action::EvalCore`.
pub(crate) async fn invoke_function_tco(
    ctx: &CallContext<'_>,
) -> EvalResult<(Arc<Spanned<CoreExpr>>, Arc<EvalFrame>)> {
    // bind_args_thunks builds an EvalFrame for the call frame from the bound params.
    let frame = bind_args_thunks(
        ctx.params,
        ctx.positional,
        ctx.named,
        Arc::clone(&ctx.closure_env),
        ctx.ctx,
        &ctx.call_span,
    )
    .await
    .map_err(|mut e| {
        e.set_arity_callee(ctx.call_span.name.clone());
        e
    })?;

    Ok((Arc::clone(ctx.body), frame))
}

/// Validate function arguments, build a call-frame EvalFrame, and return it.
///
/// Handles arity validation, default params, variadic params, and system-injected
/// named args. The returned EvalFrame carries the bound params and closure captures
/// for use with `Thunk::core_expr` and `EvalFrame`-based variable lookup.
pub(crate) async fn bind_args_thunks(
    params: &[Param],
    positional: &[Arc<Thunk>],
    named: Option<&IndexMap<String, Arc<Thunk>>>,
    closure_env: Arc<Vec<Arc<Thunk>>>,
    ctx: &Arc<EvalContext>,
    call_span: &Span,
) -> EvalResult<Arc<EvalFrame>> {
    // BIND-SPLIT: Classify params using resolved_type and variadic flag.
    // Typed variadics have variadic=true and a concrete resolved_type (not Unknown/None).
    // Untyped rest has variadic=true and resolved_type=None (or Unknown).
    // Fixed params have variadic=false.
    let mut regular_params: Vec<&Param> = Vec::new();
    let mut typed_variadic_params: Vec<&Param> = Vec::new();
    let mut rest_param: Option<&Param> = None;
    for p in params.iter() {
        if p.variadic {
            match &p.resolved_type {
                Some(ty) if !matches!(ty, Type::Unknown) => {
                    typed_variadic_params.push(p);
                }
                _ => rest_param = Some(p),
            }
        } else {
            regular_params.push(p);
        }
    }
    let max_positional = regular_params.len();
    let has_any_variadic = !typed_variadic_params.is_empty() || rest_param.is_some();

    // BIND-ARITY: Per-parameter coverage check (Kotlin model)
    // Each required parameter must be reachable via positional index OR named argument
    let mut required_count = 0;
    for (i, param) in regular_params.iter().enumerate() {
        let is_required = get_default(param).is_none();
        if is_required {
            required_count += 1;
            let covered_positionally = i < positional.len();
            let covered_by_name = named.map(|n| n.contains_key(&param.name)).unwrap_or(false);
            if !covered_positionally && !covered_by_name {
                return Err(EvalError::missing_required_param(
                    param.name.clone(),
                    call_span.clone(),
                )
                .into());
            }
        }
    }

    // Without any variadic: positional args must not exceed max_positional
    if !has_any_variadic && positional.len() > max_positional {
        // Use Range when there are optional params, Exact when all params are required
        let expected = if required_count < max_positional {
            ArityBound::Range(required_count, max_positional)
        } else {
            ArityBound::Exact(max_positional)
        };
        let param_names: Vec<String> = regular_params.iter().map(|p| p.name.clone()).collect();
        let mut err =
            EvalError::arity_mismatch_bound(expected, positional.len(), call_span.clone());
        err.set_arity_params(param_names);
        return Err(err.into());
    }

    // BIND-NAMED-VALIDATE: Check named args against params before filling slots.
    //
    // BIND-SYSTEM: System-injected named args (names containing '∷') are excluded from
    // all user-visible named-arg validation. The '∷' separator is a Unicode character
    // that cannot appear in parser-produced identifiers, so these names can only
    // originate from Rust runtime code (e.g. the @Expr macro implicit-arg injection).
    // This makes the binding unconditional and invisible to tinct code.
    if let Some(named_args) = named {
        for (name, _thunk_id) in named_args {
            // Skip system-injected args (contain '∷').
            if name.contains('∷') {
                continue;
            }
            // C-NO-OVERLAP and C-NAMED-VALID in one position() call
            match regular_params.iter().position(|p| &p.name == name) {
                Some(idx) if idx < positional.len() => {
                    // C-NO-OVERLAP: named arg targets a positionally-bound parameter
                    return Err(Box::new(EvalError::named_arg_conflict(
                        name.clone(),
                        call_span.clone(),
                    )));
                }
                Some(_) => {
                    // Valid: named arg targets an existing param that wasn't positionally bound.
                }
                None => {
                    if has_any_variadic {
                        // Unmatched named arg goes into the rest bucket (see BIND-VARIADIC below).
                    } else {
                        // No variadic param: raise E022
                        let valid_params: Vec<String> =
                            regular_params.iter().map(|p| p.name.clone()).collect();
                        return Err(Box::new(EvalError::unknown_named_arg(
                            name.clone(),
                            valid_params,
                            call_span.clone(),
                        )));
                    }
                }
            }
        }
    }

    // Build param slots as a Vec<Arc<Thunk>> indexed by param.slot.
    // EvalFrame::for_function_call(closure_env, params) creates a frame where
    // VarAddr::Parameter(i) resolves params[i].
    let slot_count = params.len();
    let mut param_slots: Vec<Option<Arc<Thunk>>> = vec![None; slot_count];

    // BIND-POSITIONAL + BIND-NAMED: Fill each regular param slot.
    // Use p.slot (the resolver-assigned parameter index) so that slots are filled at the
    // exact position the resolver reserved for each param.
    //
    // For defaults (SurfaceNode), lower to CoreExpr via lower::lower and wrap as a
    // Thunk::core_expr for lazy evaluation with an empty frame at force time.
    for (i, param) in regular_params.iter().enumerate() {
        let slot = param.slot as usize;
        if i < positional.len() {
            // Positional arg: use Arc<Thunk> directly.
            param_slots[slot] = Some(Arc::clone(&positional[i]));
        } else if let Some(named_args) = named {
            if let Some(named_thunk) = named_args.get(&param.name) {
                // Named arg: use Arc<Thunk> directly.
                param_slots[slot] = Some(Arc::clone(named_thunk));
            } else if let Some(default_node) = get_default(param) {
                // Default param: lower and wrap as a CoreExpr thunk with empty frame.
                let (lowered_default, lower_diags) = crate::lower::lower(
                    &default_node,
                    ctx.scope_frames.as_ref().map(|v| v.as_slice()),
                );
                if let Some(err) = crate::eval_materialize::lower_errors_to_eval_error(lower_diags)
                {
                    return Err(err);
                }
                let default_thunk = Arc::new(Thunk::core_expr(
                    Arc::new(lowered_default),
                    EvalFrame::empty(),
                    Arc::clone(ctx),
                    call_span.clone(),
                ));
                param_slots[slot] = Some(default_thunk);
            }
            // else: required param with no coverage — already caught by arity check.
        } else if let Some(default_node) = get_default(param) {
            // Default param (no named args provided).
            let (lowered_default, lower_diags) = crate::lower::lower(
                &default_node,
                ctx.scope_frames.as_ref().map(|v| v.as_slice()),
            );
            if let Some(err) = crate::eval_materialize::lower_errors_to_eval_error(lower_diags) {
                return Err(err);
            }
            let default_thunk = Arc::new(Thunk::core_expr(
                Arc::new(lowered_default),
                EvalFrame::empty(),
                Arc::clone(ctx),
                call_span.clone(),
            ));
            param_slots[slot] = Some(default_thunk);
        }
        // else: required param with no arg — already caught by arity check.
    }

    // BIND-VARIADIC: Route excess positional args and unmatched named args into buckets.
    //
    // When there are typed variadic params (`...xs@String ...ns@Int ...rest`):
    //   - Each excess positional arg is materialized to inspect its runtime type.
    //   - It is placed in the first typed bucket whose type it matches (declaration order).
    //   - If no typed bucket matches, it falls into the untyped rest bucket.
    //   - If there is no rest bucket and no typed bucket matches, raise an arity error.
    //   Materializing here is a necessary strictness point: the type of the value determines
    //   which bucket it routes into. Analogous to TypeAssert, which also forces evaluation
    //   at the annotation site.
    //
    // When there are no typed buckets (unannotated `...args` only), no materialization
    // occurs: all excess positionals and unmatched named args flow into rest Dict as-is.
    // Materialization is only necessary to inspect the value's runtime type for bucket dispatch.
    //
    // Named args always go into the rest bucket (keyed by their string name). They are not
    // type-discriminated into typed buckets because their names carry caller intent.
    //
    // Typed buckets are bound as lazy Seq cons-lists (Value::Variant Seq.Cons cells).
    // The rest bucket is bound as Dict{int: positional, string: named}.
    if has_any_variadic {
        let extra_positionals = &positional[max_positional.min(positional.len())..];

        // Collect typed bucket Types for dispatch.
        // Use p.resolved_type (set by the type checker) rather than re-parsing the annotation.
        // Empty when there are no typed variadics (single unannotated rest case).
        let bucket_types: Vec<Type> = typed_variadic_params
            .iter()
            .map(|p| p.resolved_type.clone().unwrap_or(Type::Unknown))
            .collect();

        // Accumulate Arc<Thunk> for each typed bucket (in declaration order).
        let mut typed_buckets: Vec<Vec<Arc<Thunk>>> = vec![Vec::new(); typed_variadic_params.len()];
        // Accumulate rest bucket: integer-keyed positionals + string-keyed named.
        let mut rest_dict: IndexMap<HashableValue, Arc<Thunk>> = IndexMap::new();
        let mut rest_int_key: i64 = 0;

        // BIND-VARIADIC: Route each excess positional arg to its bucket.
        //
        // Materialization is only needed when there are typed buckets to route into.
        // When bucket_types is empty (unannotated rest-only case), args flow directly
        // into rest_dict without forcing — preserving lazy evaluation.
        for arg_thunk in extra_positionals.iter() {
            let mut routed = false;

            if !bucket_types.is_empty() {
                // Materialize to inspect the runtime type for bucket dispatch.
                let value = materialize(arg_thunk, Some(call_span), ctx).await?;

                // Try each typed bucket in declaration order — first match wins.
                for (bucket_idx, bucket_ty) in bucket_types.iter().enumerate() {
                    if value_matches_type(&value, bucket_ty, ctx) {
                        typed_buckets[bucket_idx].push(Arc::clone(arg_thunk));
                        routed = true;
                        break;
                    }
                }
            }

            if !routed {
                if rest_param.is_some() {
                    rest_dict.insert(HashableValue::Int(rest_int_key), Arc::clone(arg_thunk));
                    rest_int_key += 1;
                } else {
                    // No rest bucket and no typed bucket matched: arg cannot be accepted.
                    let expected = ArityBound::Exact(max_positional);
                    return Err(EvalError::arity_mismatch_bound(
                        expected,
                        positional.len(),
                        call_span.clone(),
                    )
                    .into());
                }
            }
        }

        // Route unmatched named args into the rest bucket (not type-discriminated).
        if let Some(named_args) = named {
            for (name, named_thunk) in named_args {
                if name.contains('∷') {
                    continue;
                }
                if regular_params.iter().any(|p| &p.name == name) {
                    continue;
                }
                rest_dict.insert(
                    HashableValue::Str(Arc::from(name.as_str())),
                    Arc::clone(named_thunk),
                );
            }
        }

        // BIND-RESULT: Bind each typed variadic bucket as a lazy Seq cons-list.
        //
        // Produces Value::Variant Seq.Cons/Seq.End cells matching the prelude's Seq type.
        // An empty bucket binds to Seq.End (unit variant).
        //
        // Use p.slot (resolver-assigned) for each typed variadic param.
        for (bucket_args, p) in typed_buckets.into_iter().zip(typed_variadic_params.iter()) {
            let slot = p.slot as usize;
            let seq_thunk = build_seq(bucket_args.as_slice(), call_span);
            param_slots[slot] = Some(seq_thunk);
        }

        // BIND-RESULT: Bind the untyped rest bucket as a Dict (if present).
        // Use rest_param.slot (resolver-assigned) directly.
        if let Some(rp) = rest_param {
            let rest_slot = rp.slot as usize;
            let rest_thunk = Arc::new(Thunk::value(Value::Dict(rest_dict), call_span.clone()));
            param_slots[rest_slot] = Some(rest_thunk);
        }
    }

    // Collect param_slots into a Vec<Arc<Thunk>>.
    // Invariant: all slots must be filled after arity checks above. An unfilled slot
    // indicates a bug in the arity checking or slot-filling logic above.
    let params_vec: Vec<Arc<Thunk>> = param_slots
        .into_iter()
        .map(|opt| opt.expect("param slot invariant violated: unfilled slot after arity check"))
        .collect();

    Ok(EvalFrame::for_function_call(closure_env, params_vec))
}

/// Build a lazy Seq cons-list from a slice of `Arc<Thunk>`.
///
/// Produces `Value::Variant` cells matching the prelude's `Seq` type declaration:
///   `Seq: [type [let a] Cons: [head: a  tail: [Seq a]] End]`
///
/// Typed variadic arguments are auto-indexed dicts — a Rust primitive. Prelude
/// decides what to do with them (iterate with `each`, convert to Seq, etc.).
/// Rust has no knowledge of Seq, Cons, End, or any prelude-specific type.
fn build_seq(args: &[Arc<Thunk>], span: &Span) -> Arc<Thunk> {
    let mut dict: IndexMap<crate::value::HashableValue, Arc<Thunk>> = IndexMap::new();
    for (i, thunk) in args.iter().enumerate() {
        dict.insert(
            crate::value::HashableValue::Int(i as i64),
            Arc::clone(thunk),
        );
    }
    Arc::new(Thunk::value(Value::Dict(dict), span.clone()))
}

/// Extract the default value node from a param's annotation, if present.
///
/// `default:` is specified via PropertyDict annotation with a "default" key, e.g.:
/// `[fn [let x@[default: 42]] ...]`
///
/// Returns the `Arc<SurfaceNode>` of the default expression directly.
/// The caller lowers this to CoreExpr via `lower::lower` and wraps the result in a
/// `Thunk::core_expr` for lazy evaluation in the default scope.
pub(crate) fn get_default(param: &Param) -> Option<Arc<SurfaceNode>> {
    param
        .annotation
        .as_ref()
        .and_then(|ann| ann.node.get_property(DEFAULT_ANNOTATION_KEY))
        .map(Arc::clone)
}


//! Function call evaluation: argument binding, default parameters, and variadic support.

use std::rc::Rc;
use std::sync::{Arc, RwLock};

use indexmap::IndexMap;
use smallvec::SmallVec;

use crate::ast::{Expr, NamedArg, Param, Span, Spanned};
use crate::error::{ArityBound, EvalError, EvalResult};
use crate::value::{Environment, Thunk, Value};

// Import eval function and context from eval module
// Note: this creates a circular dependency, but it's safe because
// eval.rs imports invoke_function/CallContext from this module, while
// this module imports eval/EvalContext from eval.rs. Neither module's
// initialization depends on the other.
use crate::eval::{eval, materialize, EvalContext};

const DEFAULT_ANNOTATION_KEY: &str = "default";

/// Extract a human-readable label from a function expression for stack frames.
///
/// Returns `None` for anonymous calls that add no diagnostic value.
/// When the expression is a desugared `$_` lambda (synthesized by `desugar.rs`),
/// a label is returned so stack traces distinguish sugar-generated closures from
/// user-written `[fn ...]` forms.
///
/// Phase 2 format: implied calls use `[name ...]` (no `call` keyword, no `$` sigil).
pub(crate) fn func_label(expr: &Expr) -> Option<Arc<str>> {
    match expr {
        Expr::VarRef { name, .. } => Some(Arc::from(format!("[{name} ...]").as_str())),
        Expr::DotAccess { .. } => Some(Arc::from("[<dot-access> ...]")),
        Expr::Fn {
            desugared: true, ..
        } => Some(Arc::from("[<auto-generated lambda> ...]")),
        _ => None,
    }
}

/// Evaluate a call expression: return a PendingCall thunk that defers function dispatch.
///
/// Now returns a PendingCall thunk; function dispatch is deferred to the PendingCallDispatch
/// continuation in `run()`. This diverges from the [FORCE-CALL] rule in doc/08-evaluation.md,
/// which described the old eager dispatch model — the rule has been updated to reflect the
/// current lazy dispatch design that enables unlimited tail-call optimization.
///
/// Neither the function nor any argument is materialized here. The PendingCallDispatch
/// continuation forces `func_thunk` when the result is needed, then dispatches to
/// `invoke_function` (user functions) or the builtin handler.
pub(crate) fn eval_call(
    func_expr: &Spanned<Expr>,
    args: &[Rc<Spanned<Expr>>],
    named_args: &[Spanned<NamedArg>],
    env: &Arc<RwLock<Environment>>,
    ctx: &Arc<EvalContext>,
    call_span: &Span,
) -> EvalResult<Arc<Thunk>> {
    // Evaluate the function as a thunk (lazy — no materialization).
    let func_thunk = eval(Rc::new(func_expr.clone()), Arc::clone(env), ctx)?;

    // Wrap arguments as unevaluated thunks (lazy). This ensures expressions
    // like $xs[$i] in unselected $if branches are never evaluated.
    // SmallVec<[_; 4]>: most calls have ≤4 args, avoiding heap allocation.
    let pos_thunks: SmallVec<[Arc<Thunk>; 4]> = args
        .iter()
        .map(|arg| {
            Arc::new(Thunk::new_unevaluated(
                Rc::clone(arg),
                Arc::clone(env),
                Arc::clone(ctx),
                arg.span,
            ))
        })
        .collect();
    let named_thunks = if named_args.is_empty() {
        IndexMap::new()
    } else {
        let mut m = IndexMap::with_capacity(named_args.len());
        for na in named_args {
            m.insert(
                na.node.name.clone(),
                Arc::new(Thunk::new_unevaluated(
                    Rc::clone(&na.node.value),
                    Arc::clone(env),
                    Arc::clone(ctx),
                    na.node.value.span,
                )),
            );
        }
        m
    };

    // Return PendingCall thunk — function dispatch happens iteratively in run().
    // PendingCallDispatch forces func_thunk, matches Function vs Builtin, and invokes.
    // For tail-recursive functions, the loop depth stays constant — prerequisite for unlimited TCO via CEK machine.
    Ok(Arc::new(Thunk::new_pending_call(
        func_thunk,
        pos_thunks.into_vec(),
        named_thunks,
        *call_span,
        Arc::clone(env), // caller_env: used for default param evaluation
        *call_span,
        func_label(&func_expr.node),
        Arc::clone(ctx),
    )))
}

/// Arguments for invoking a user-defined function.
///
/// `default_env` is the environment used to evaluate default expressions for
/// optional params. For normal calls this is the caller's environment; for
/// `apply` it is the closure environment.
pub struct CallContext<'a> {
    pub params: &'a [Param],
    pub body: &'a Rc<Spanned<Expr>>,
    pub closure_env: &'a Arc<RwLock<Environment>>,
    pub positional: &'a [Arc<Thunk>],
    pub named: Option<&'a IndexMap<String, Arc<Thunk>>>,
    pub default_env: &'a Arc<RwLock<Environment>>,
    pub call_span: Span,
    /// Label for stack traces (e.g. "call $f"). `None` for anonymous calls.
    pub origin: Option<Arc<str>>,
    pub ctx: &'a Arc<EvalContext>,
}

/// Invoke a user-defined function with pre-evaluated thunks.
///
/// Binds positional and named args to function params (respecting defaults and
/// variadics), then wraps the body as an unevaluated thunk. This is the shared
/// call path for both `eval_call` and `builtin_apply`.
///
/// Special case: variant constructors (marked by VARIANT_TAG_MARKER in closure env)
/// wrap their single argument in a Value::Variant instead of normal function invocation.
pub fn invoke_function(ctx: &CallContext) -> EvalResult<Arc<Thunk>> {
    // Marker for variant constructor functions (defined in eval.rs)
    const VARIANT_TAG_MARKER: &str = "__variant_tag__";

    // Check if this is a variant constructor
    if let Some(tag_thunk) = ctx.closure_env.read().unwrap().get(VARIANT_TAG_MARKER) {
        // Validate: variant constructors take exactly one positional argument, no named args
        if ctx.positional.len() != 1 {
            return Err(EvalError::arity_mismatch(1, ctx.positional.len(), ctx.call_span).into());
        }

        if ctx.named.map_or(false, |n| !n.is_empty()) {
            return Err(EvalError::named_arg_rejected(
                "variant constructor".to_string(),
                ctx.call_span,
            )
            .into());
        }

        // Extract the tag from the marker
        let tag_value = materialize(&tag_thunk, Some(&ctx.call_span), ctx.ctx)?;
        let tag = match tag_value {
            Value::String {
                ref source,
                start,
                end,
            } => source[start..end].to_string(),
            _ => {
                return Err(EvalError::internal(
                    "variant constructor tag must be a string".to_string(),
                    ctx.call_span,
                )
                .into());
            }
        };

        // Store the payload thunk in arena (keeps it lazy)
        let payload_id = ctx.ctx.alloc_thunk(Arc::clone(&ctx.positional[0]));

        // Create the variant value
        let variant = Value::Variant {
            tag,
            payload: Some(payload_id),
        };

        return Ok(Arc::new(Thunk::new_materialized(variant, ctx.call_span)));
    }

    // Normal function invocation
    let call_env = bind_args_thunks(
        ctx.params,
        ctx.positional,
        ctx.named,
        ctx.default_env,
        ctx.closure_env,
        ctx.ctx,
        &ctx.call_span,
    )?;
    let mut thunk = Thunk::new_unevaluated(
        Rc::clone(ctx.body),
        call_env,
        Arc::clone(ctx.ctx),
        ctx.call_span,
    );
    if let Some(ref label) = ctx.origin {
        thunk = thunk.with_origin(Arc::clone(label));
    }
    Ok(Arc::new(thunk))
}

/// Bind pre-evaluated thunks to function parameters. Returns the new call environment.
///
/// Handles positional args, named args (params with `default:` annotation),
/// and variadic params (`...name`).
pub(crate) fn bind_args_thunks(
    params: &[Param],
    positional: &[Arc<Thunk>],
    named: Option<&IndexMap<String, Arc<Thunk>>>,
    default_env: &Arc<RwLock<Environment>>,
    closure_env: &Arc<RwLock<Environment>>,
    ctx: &Arc<EvalContext>,
    call_span: &Span,
) -> EvalResult<Arc<RwLock<Environment>>> {
    let call_env = Arc::new(RwLock::new(Environment::with_parent(Arc::clone(
        closure_env,
    ))));

    // BIND-SPLIT: Separate the variadic param (if any) from regular params
    let (regular_params, variadic_param) = split_variadic(params);
    let max_positional = regular_params.len();

    // BIND-ARITY: Per-parameter coverage check (Kotlin model)
    // Each required parameter must be reachable via positional index OR named argument
    let mut required_count = 0;
    for (i, param) in regular_params.iter().enumerate() {
        let is_required = get_default(param).is_none();
        if is_required {
            required_count += 1;
            let covered_positionally = i < positional.len();
            let covered_by_name = named.map(|n| n.contains_key(&param.name)).unwrap_or(false);
            if !covered_positionally && !covered_by_name {
                return Err(
                    EvalError::missing_required_param(param.name.clone(), *call_span).into(),
                );
            }
        }
    }

    // Without variadic: positional args must not exceed max_positional
    if variadic_param.is_none() && positional.len() > max_positional {
        // Use Range when there are optional params, Exact when all params are required
        let expected = if required_count < max_positional {
            ArityBound::Range(required_count, max_positional)
        } else {
            ArityBound::Exact(max_positional)
        };
        return Err(EvalError::arity_mismatch_bound(expected, positional.len(), *call_span).into());
    }

    // BIND-POSITIONAL: Bind args to params following C-PRIORITY chain
    for (i, param) in regular_params.iter().enumerate() {
        let thunk = if i < positional.len() {
            // Case (i): positional arg at index i
            Arc::clone(&positional[i])
        } else if let Some(named_thunk) = named.and_then(|n| n.get(&param.name)) {
            // Case (ii): named arg fills gap beyond positional args
            // (Kotlin model: ANY param can be named, not just optional)
            Arc::clone(named_thunk)
        } else if let Some(default_val) = get_default(param) {
            // Case (iii): use default value
            eval(Rc::new(default_val), Arc::clone(default_env), ctx)?
        } else {
            // Unreachable: BIND-ARITY guarantees every required param is covered
            unreachable!(
                "BIND-ARITY should have caught missing required param '{}'",
                param.name
            );
        };
        call_env.write().unwrap().insert(param.name.clone(), thunk);
    }

    // BIND-NAMED: Validation only (all bindings were already done in BIND-POSITIONAL)
    //
    // Why two checks? BIND-POSITIONAL silently resolves conflicts via priority
    // (positional wins over named), but the caller likely made a mistake if they
    // supplied both. This second pass detects that mistake and reports it as an
    // error (C-NO-OVERLAP), while also catching named args that don't match any
    // parameter at all (C-NAMED-VALID).
    if let Some(named_args) = named {
        for (name, _) in named_args {
            // Single scan: C-NO-OVERLAP and C-NAMED-VALID in one position() call
            match regular_params.iter().position(|p| &p.name == name) {
                Some(idx) if idx < positional.len() => {
                    // C-NO-OVERLAP: named arg targets a positionally-bound parameter
                    return Err(Box::new(EvalError::named_arg_conflict(
                        name.clone(),
                        *call_span,
                    )));
                }
                Some(_) => {
                    // Valid: named arg targets an existing param that wasn't positionally bound
                    // (idx >= positional.len(), verified by guard above). Continue to next arg.
                    continue;
                }
                None => {
                    // C-NAMED-VALID: named arg must target an existing parameter
                    // (Kotlin model: ANY param can be named, not just optional params)
                    let valid_params: Vec<String> =
                        regular_params.iter().map(|p| p.name.clone()).collect();
                    return Err(Box::new(EvalError::unknown_named_arg(
                        name.clone(),
                        valid_params,
                        *call_span,
                    )));
                }
            }
        }
    }

    // BIND-VARIADIC: Collect excess positional args into a lazy Seq cons-list.
    // Empty variadic = Value::Dict({}) (the standard Seq nil sentinel).
    // Non-empty: build cons-list right-to-left so the first arg becomes the outermost head.
    if let Some(var_param) = variadic_param {
        let start = max_positional.min(positional.len());
        let variadic_args = &positional[start..];
        // Nil sentinel: empty dict is the standard end-of-Seq marker.
        let nil = Arc::new(Thunk::new_materialized(
            Value::Dict(IndexMap::new()),
            *call_span,
        ));
        let seq_thunk = variadic_args.iter().rev().fold(nil, |tail, head_arg| {
            let head_id = ctx.alloc_thunk(Arc::clone(head_arg));
            let tail_id = ctx.alloc_thunk(Arc::clone(&tail));
            Arc::new(Thunk::new_materialized(
                Value::Seq {
                    head: head_id,
                    tail: tail_id,
                },
                *call_span,
            ))
        });
        call_env
            .write().unwrap()
            .insert(var_param.name.clone(), seq_thunk);
    }

    Ok(call_env)
}

/// Split params into (regular, optional variadic).
pub(crate) fn split_variadic(params: &[Param]) -> (&[Param], Option<&Param>) {
    match params.last() {
        Some(p) if p.variadic => (&params[..params.len() - 1], Some(p)),
        _ => (params, None),
    }
}

/// Extract the default value expression from a param's annotation, if present.
/// default: is specified via PropertyDict annotation with a "default" key.
pub(crate) fn get_default(param: &Param) -> Option<Spanned<Expr>> {
    param
        .annotation
        .as_ref()
        .and_then(|ann| ann.node.get_property(DEFAULT_ANNOTATION_KEY))
        .cloned()
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::test_util::sp;

    #[test]
    fn test_func_label_varref() {
        // Test func_label with a VarRef expression
        let expr = Expr::var_ref("my_func".to_string());
        let label = func_label(&expr);
        assert_eq!(label.as_deref(), Some("[my_func ...]"));
    }

    #[test]
    fn test_func_label_desugared_lambda() {
        // Test func_label with a desugared lambda
        let expr = Expr::Fn {
            return_ann: None,
            params: vec![],
            body: Arc::new(sp(Expr::Int(42))),
            desugared: true,
        };
        let label = func_label(&expr);
        assert!(label
            .as_deref()
            .unwrap_or("")
            .contains("auto-generated lambda"));
    }

    #[test]
    fn test_func_label_regular_lambda() {
        // Test func_label with a regular (non-desugared) lambda — anonymous, returns None
        let expr = Expr::Fn {
            return_ann: None,
            params: vec![],
            body: Arc::new(sp(Expr::Int(42))),
            desugared: false,
        };
        let label = func_label(&expr);
        assert_eq!(label, None);
    }
}

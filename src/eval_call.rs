/// Return `true` if `tv` is a TypeValue.Unknown — either the bootstrap sentinel (empty dict)
/// or a proper `Value::Variant { ctor: "TypeValue.Unknown" }` after the repr protocol runs.
pub(crate) fn is_typevalue_unknown(tv: &Arc<Value>) -> bool {
    match tv.as_ref() {
        Value::Variant { ctor, .. } => ctor.as_ref() == TV_UNKNOWN,
        // Bootstrap sentinel: unknown_type_val() is an empty dict before repr protocol runs.
        Value::Dict { entries, .. } => entries.is_empty(),
        _ => false,
    }
}

const DEFAULT_ANNOTATION_KEY: &str = ANNOTATION_KEY_DEFAULT;

/// Extract a human-readable label from a CoreExpr function position for stack frames.
///
/// Operates on `CoreExpr` directly so `eval_call_core` does not need any
/// conversion solely for the label.
pub(crate) fn func_label_core(expr: &CoreExpr) -> Option<Arc<str>> {
    match expr {
        CoreExpr::Var { name, .. } => Some(Arc::from(name.as_str())),
        CoreExpr::Fn {
            desugared: true, ..
        } => Some(Arc::from("<auto-generated lambda>")),
        _ => None,
    }
}

/// Evaluate a CoreExpr::Call natively — return a PendingCall thunk without round-tripping
/// the function or argument expressions back through `Expr`.
///
/// This is the Parts-B+E migration path for `CoreExpr::Call` in `eval_core_expr`.
/// It mirrors `eval_call` exactly but accepts `Arc<Spanned<CoreExpr>>` slices directly,
/// avoiding the per-argument `core_expr_to_expr` allocation that the old bridge code
/// performed in `eval_core_expr`.
///
/// # Implementation notes
///
/// Arguments use `Thunk::core_expr` (storing `Arc<Spanned<CoreExpr>>` directly)
/// — no per-arg allocation. The function expression is evaluated directly via
/// `eval_core_expr`, avoiding bridge round-trips.
pub(crate) async fn eval_call_core(
    func_expr: &Spanned<CoreExpr>,
    args: &[Arc<Spanned<CoreExpr>>],
    named_args: &[Spanned<CoreNamedArg>],
    caller_env_id: u32,
    ctx: &Arc<EvalContext>,
    call_span: &Span,
    original_call: Arc<Spanned<CoreExpr>>,
    caller_frame: &Arc<EvalFrame>,
) -> EvalResult<Arc<Thunk>> {
    let func_thunk = eval_core_expr(func_expr, caller_frame, ctx).await?;

    // Wrap positional arguments as Unevaluated CoreExpr thunks (Arc<Thunk> directly).
    // Use the caller's EvalFrame so that Dispatch/ClosureCapture variable
    // references inside argument expressions resolve against the call site's scope.
    let pos_args: Vec<Arc<Thunk>> = args
        .iter()
        .map(|arg| {
            Arc::new(Thunk::core_expr(
                Arc::clone(arg),
                Arc::clone(caller_frame),
                Arc::clone(ctx),
                arg.span.clone(),
            ))
        })
        .collect();

    // Wrap named arguments as Unevaluated CoreExpr thunks (Arc<Thunk> directly).
    let named_args_map = if named_args.is_empty() {
        IndexMap::new()
    } else {
        let mut m = IndexMap::with_capacity(named_args.len());
        for na in named_args {
            let t = Arc::new(Thunk::core_expr(
                Arc::clone(&na.node.value),
                Arc::clone(caller_frame),
                Arc::clone(ctx),
                na.node.value.span.clone(),
            ));
            m.insert(na.node.name.clone(), t);
        }
        m
    };

    // Return PendingCall thunk — function dispatch deferred to PendingCallDispatch in run().
    // Attach the function label (if known) to the call span for blame tracking.
    let thunk_span = if let Some(label) = func_label_core(&func_expr.node) {
        call_span.clone().with_name(label)
    } else {
        call_span.clone()
    };
    Ok(Arc::new(Thunk::fn_call(
        func_thunk,
        pos_args,
        named_args_map,
        thunk_span,
        crate::value::FnCallSpec {
            call_span: call_span.clone(),
            caller_env_id,
            ctx: Arc::clone(ctx),
            original_call,
        },
    )))
}

/// Arguments for invoking a user-defined function.
///
/// `clauses` is the full clause list from `Value::Function.clauses`.
/// `invoke_function` iterates clauses via `try_clause` to find the first matching one.
/// `closure_env` is the captured environment built at function-definition time.
pub struct CallContext<'a> {
    pub clauses: &'a Arc<Vec<CoreClause>>,
    /// Captured closure environment (replaces closure_env_id u32 + scope_arena lookup).
    pub closure_env: Arc<Vec<Arc<Thunk>>>,
    pub positional: &'a [Arc<Thunk>],
    pub named: Option<&'a IndexMap<String, Arc<Thunk>>>,
    /// Call site span — `name` field carries the function label for blame tracking.
    pub call_span: Span,
    pub ctx: &'a Arc<EvalContext>,
}

/// Try to match a single function clause against the provided arguments.
///
/// Returns `Ok(Some(frame))` when the clause matches — the frame is ready for the body.
/// Returns `Ok(None)` when the clause does not match (wrong arity, type guard, pattern, or guard fails).
/// Returns `Err(...)` on a hard evaluation error during type guard or pattern materialization.
///
/// Matching rules (in order):
/// 1. **Arity**: count non-variadic params; if `args.len()` does not match → `Ok(None)`.
/// 2. **Type guards**: for each param whose `resolved_type` is `Some(tv)` and not Unknown,
///    materialize the corresponding arg and check `value_matches_type`. Mismatch → `Ok(None)`.
///    Params with `resolved_type = None` or Unknown are wildcards that always pass.
/// 3. **Lowered pattern**: if `clause.lowered_pattern.is_some()`, evaluate the structural
///    pattern against `args[0]`. Pattern mismatch → `Ok(None)`. The current lowerer never
///    produces `CoreExpr::Fn` clauses with `lowered_pattern = Some(...)`, so this path is
///    unreachable in practice, but is implemented correctly.
/// 4. **Guard expression**: if `clause.guard.is_some()`, bind args and evaluate the guard in
///    the bound frame. Falsy guard → `Ok(None)`. Returns the bound frame directly when the
///    guard passes, skipping the redundant bind in step 5.
/// 5. **All checks pass**: call `bind_args_thunks` and return the resulting frame.
pub(crate) async fn try_clause(
    clause: &CoreClause,
    args: &[Arc<Thunk>],
    named: Option<&IndexMap<String, Arc<Thunk>>>,
    closure_env: Arc<Vec<Arc<Thunk>>>,
    ctx: &Arc<EvalContext>,
    call_span: &Span,
) -> EvalResult<Option<Arc<EvalFrame>>> {
    // Convert CoreParam → Param for use with bind_args_thunks.
    // This mirrors the conversion in the CoreExpr::Fn evaluator arm (eval_core.rs).
    let params: Vec<Param> = clause
        .params
        .iter()
        .map(|p| Param {
            name: p.node.name.clone(),
            annotation: p.node.annotation.clone(),
            variadic: p.node.variadic,
            slot: p.node.slot,
            resolved_type: p.node.resolved_type.clone(),
        })
        .collect();

    // Step 1 — Arity check: determine whether the arg count is compatible with this clause.
    //
    // For clause matching (vs. single-clause error reporting) we return Ok(None) for any
    // incompatible arity so the caller can try the next clause. The rules mirror bind_args_thunks
    // classification but are applied as a filter rather than a hard error:
    //
    // - required_count: non-variadic params with no default expression.
    // - max_positional: total non-variadic params (required + optional-with-default).
    // - has_variadic: true when any param is variadic (absorbs excess positionals).
    //
    // Incompatible cases:
    //   some required param is not covered positionally or by a named arg
    //   args.len() > max_positional AND !has_variadic — too many positional args
    //
    // Named args must be considered when checking required-param coverage: a named arg
    // `kind: "Operator"` covers the required param `kind` even when args is empty.
    // This matches the Kotlin-model coverage check in bind_args_thunks (BIND-ARITY).
    let max_positional = params.iter().filter(|p| !p.variadic).count();
    let has_variadic = params.iter().any(|p| p.variadic);

    // Check that every required non-variadic param is covered positionally or by a named arg.
    for (i, param) in params.iter().filter(|p| !p.variadic).enumerate() {
        if get_default(param).is_none() {
            // Required param: must be reachable positionally or by name.
            let covered_positionally = i < args.len();
            let covered_by_name = named.map(|n| n.contains_key(&param.name)).unwrap_or(false);
            if !covered_positionally && !covered_by_name {
                return Ok(None);
            }
        }
    }

    if !has_variadic && args.len() > max_positional {
        return Ok(None);
    }

    // Step 2 — Type guard params: materialize and check type for annotated params.
    // Materialization here is a necessary strictness point: type dispatch requires
    // knowing the runtime type, analogous to the typed-variadic bucket routing in
    // bind_args_thunks. Only params with a concrete resolved_type (not Unknown/None) are checked.
    for (i, param) in params.iter().enumerate() {
        let Some(tv) = &param.resolved_type else {
            continue; // No annotation → wildcard, always matches.
        };
        if is_typevalue_unknown(tv) {
            continue; // TypeValue.Unknown → wildcard, always matches.
        }
        let Some(arg) = args.get(i) else {
            continue; // Arg absent — arity check above handles this case.
        };
        let value = materialize(arg, Some(call_span), ctx).await?;
        if !value_matches_type(&value, tv, ctx) {
            return Ok(None); // Type mismatch — this clause does not apply.
        }
    }

    // Step 2b — Named arg type guard: same check as Step 2 but for named arguments.
    // A named arg may supply a value for an annotated param that was not covered positionally.
    // Without this check, named args bypass type dispatch entirely.
    if let Some(named_map) = named {
        for param in params.iter() {
            let Some(tv) = &param.resolved_type else {
                continue;
            };
            if is_typevalue_unknown(tv) {
                continue;
            }
            if let Some(named_thunk) = named_map.get(&param.name) {
                let value = materialize(named_thunk, Some(call_span), ctx).await?;
                if !value_matches_type(&value, tv, ctx) {
                    return Ok(None);
                }
            }
        }
    }

    // Step 3 — Lowered pattern: structural match against the first positional argument.
    // The current lowerer never produces CoreExpr::Fn clauses with lowered_pattern = Some(...)
    // (fn clauses have lowered_pattern = None; only match arm clauses set it). If a fn clause
    // ever carries a lowered_pattern, evaluate it as a structural pattern against args[0].
    if let Some(lowered_pattern) = &clause.lowered_pattern {
        // Build a pre-arm frame with the closure_env so ClosureCapture pin addresses resolve.
        let pre_frame = Arc::new(EvalFrame::for_function_call(
            Arc::clone(&closure_env),
            vec![],
        ));
        // Build the binding_map from clause.params (name → slot).
        let binding_map: IndexMap<String, u32> = clause
            .params
            .iter()
            .map(|p| (p.node.name.clone(), p.node.slot))
            .collect();
        // Materialize the first positional arg as the pattern scrutinee.
        let scrutinee = match args.first() {
            Some(arg) => materialize(arg, Some(call_span), ctx).await?,
            None => {
                // No first arg — pattern cannot match (arity would have caught zero-arg).
                return Ok(None);
            }
        };
        // Capture the structural pattern bindings for use in the arm frame.
        let pattern_bindings: Option<Vec<(u32, Arc<Thunk>)>> =
            match crate::eval_materialize::eval_case_arm_structural_pattern(
                lowered_pattern,
                &binding_map,
                &scrutinee,
                call_span.clone(),
                &pre_frame,
                ctx,
            )
            .await?
            {
                Some(bindings) => Some(bindings),
                None => {
                    // Pattern did not match — this clause does not apply.
                    return Ok(None);
                }
            };

        // If the structural pattern produced bindings, build the frame directly from them
        // (matching the `eval_materialize.rs` MatchDispatch path for case arms).
        // This ensures pattern-bound variables (e.g. `h`, `p` from [case [let h p] ...])
        // are correctly populated in the call frame rather than discarded.
        if let Some(bindings) = pattern_bindings {
            // Sort bindings by slot so params_vec is indexed contiguously.
            let mut sorted = bindings;
            sorted.sort_unstable_by_key(|(slot, _)| *slot);
            let slot_count = params
                .len()
                .max(sorted.last().map(|(s, _)| (*s as usize) + 1).unwrap_or(0));
            let mut params_vec: Vec<Option<Arc<Thunk>>> = vec![None; slot_count];
            for (slot, thunk) in sorted {
                let s = slot as usize;
                if s < params_vec.len() {
                    params_vec[s] = Some(thunk);
                }
            }
            // Fill any remaining gaps with a sentinel (should not happen for well-formed arms).
            let params_final: Vec<Arc<Thunk>> = params_vec
                .into_iter()
                .enumerate()
                .map(|(i, opt)| {
                    opt.unwrap_or_else(|| {
                        panic!(
                            "try_clause structural pattern: unfilled param slot {} \
                             — lowerer invariant violated",
                            i
                        )
                    })
                })
                .collect();
            let bound_frame = EvalFrame::for_function_call(Arc::clone(&closure_env), params_final);

            // Step 4 (guard) with pattern-bound frame.
            if let Some(guard_expr) = &clause.guard {
                let guard_thunk = eval_core_expr(guard_expr, &bound_frame, ctx).await?;
                let guard_value = materialize(&guard_thunk, Some(call_span), ctx).await?;
                if !Box::pin(call_to_match(&guard_value, ctx, call_span)).await? {
                    return Ok(None);
                }
            }
            return Ok(Some(bound_frame));
        }
    }

    // Step 4 — Guard expression: evaluate in the fully bound frame.
    // Bind args first so the guard can reference bound parameter names.
    // If the guard is falsy, this clause does not match.
    if let Some(guard_expr) = &clause.guard {
        let bound_frame = bind_args_thunks(
            &params,
            args,
            named,
            Arc::clone(&closure_env),
            ctx,
            call_span,
        )
        .await
        .map_err(|mut e| {
            e.set_arity_callee(call_span.name.clone());
            e
        })?;
        let guard_thunk = eval_core_expr(guard_expr, &bound_frame, ctx).await?;
        let guard_value = materialize(&guard_thunk, Some(call_span), ctx).await?;
        if !Box::pin(call_to_match(&guard_value, ctx, call_span)).await? {
            return Ok(None);
        }
        // Guard passed — return the already-bound frame.
        return Ok(Some(bound_frame));
    }

    // Step 5 — All checks pass: bind args and return the call frame.
    let frame = bind_args_thunks(&params, args, named, closure_env, ctx, call_span)
        .await
        .map_err(|mut e| {
            e.set_arity_callee(call_span.name.clone());
            e
        })?;
    Ok(Some(frame))
}

/// Invoke a user-defined function with pre-evaluated thunks.
///
/// Iterates over the function's clauses via `try_clause`, selecting the first
/// matching clause. Wraps the matching clause's body as an unevaluated thunk.
/// This is the shared call path for both `PendingCallDispatch` and `builtin_apply`.
///
/// Error reporting: when no clause matches, single-clause functions fall through to
/// `bind_args_thunks` directly to produce a specific arity/coverage error (e.g.
/// "missing argument for required parameter"). Multi-clause functions report
/// "no matching clause" — they may have rejected due to type dispatch rather than arity,
/// and `bind_args_thunks` on an arbitrary clause would give a misleading error.
pub async fn invoke_function(ctx: &CallContext<'_>) -> EvalResult<Arc<Thunk>> {
    for clause in ctx.clauses.iter() {
        let result = try_clause(
            clause,
            ctx.positional,
            ctx.named,
            Arc::clone(&ctx.closure_env),
            ctx.ctx,
            &ctx.call_span,
        )
        .await?;
        if let Some(frame) = result {
            let thunk = Thunk::core_expr(
                Arc::clone(&clause.body),
                frame,
                Arc::clone(ctx.ctx),
                ctx.call_span.clone(),
            );
            return Ok(Arc::new(thunk));
        }
    }
    // No clause matched.
    // For single-clause functions, fall through to bind_args_thunks to produce a specific
    // arity error (e.g. "missing argument for required parameter"). For multi-clause
    // functions, clauses may have rejected due to type dispatch; use "no matching clause".
    //
    // Single-clause: try_clause may have rejected due to type guard (Step 2) rather than
    // arity (Step 1). If bind_args_thunks also rejects, it produces the specific arity error.
    // If bind_args_thunks succeeds (type was the only reason try_clause rejected), fall through
    // to "no matching clause".
    if ctx.clauses.len() == 1 {
        let clause = &ctx.clauses[0];
        let params: Vec<Param> = clause
            .params
            .iter()
            .map(|p| Param {
                name: p.node.name.clone(),
                annotation: p.node.annotation.clone(),
                variadic: p.node.variadic,
                slot: p.node.slot,
                resolved_type: p.node.resolved_type.clone(),
            })
            .collect();
        match bind_args_thunks(
            &params,
            ctx.positional,
            ctx.named,
            Arc::clone(&ctx.closure_env),
            ctx.ctx,
            &ctx.call_span,
        )
        .await
        {
            Err(mut e) => {
                e.set_arity_callee(ctx.call_span.name.clone());
                return Err(e);
            }
            Ok(_) => {
                // bind_args_thunks succeeded: try_clause rejected for type reasons only.
                // Fall through to "no matching clause".
            }
        }
    }
    Err(EvalError::user_error(
        "no matching clause for the given arguments".to_string(),
        ctx.call_span.clone(),
    )
    .into())
}

/// TCO variant of `invoke_function` that returns the body expression and call EvalFrame
/// directly instead of creating a thunk. This allows the caller to reuse the current
/// continuation frame instead of pushing a new Memoize continuation.
///
/// Returns `(body_expr, call_frame)` so the caller can construct `Action::EvalCore`.
pub(crate) async fn invoke_function_tco(
    ctx: &CallContext<'_>,
) -> EvalResult<(Arc<Spanned<CoreExpr>>, Arc<EvalFrame>)> {
    for clause in ctx.clauses.iter() {
        let result = try_clause(
            clause,
            ctx.positional,
            ctx.named,
            Arc::clone(&ctx.closure_env),
            ctx.ctx,
            &ctx.call_span,
        )
        .await?;
        if let Some(frame) = result {
            return Ok((Arc::clone(&clause.body), frame));
        }
    }
    // No clause matched — same fallback logic as invoke_function.
    // Single-clause: try bind_args_thunks for the specific arity error.
    if ctx.clauses.len() == 1 {
        let clause = &ctx.clauses[0];
        let params: Vec<Param> = clause
            .params
            .iter()
            .map(|p| Param {
                name: p.node.name.clone(),
                annotation: p.node.annotation.clone(),
                variadic: p.node.variadic,
                slot: p.node.slot,
                resolved_type: p.node.resolved_type.clone(),
            })
            .collect();
        match bind_args_thunks(
            &params,
            ctx.positional,
            ctx.named,
            Arc::clone(&ctx.closure_env),
            ctx.ctx,
            &ctx.call_span,
        )
        .await
        {
            Err(mut e) => {
                e.set_arity_callee(ctx.call_span.name.clone());
                return Err(e);
            }
            Ok(_) => {
                // bind_args_thunks succeeded: try_clause rejected for type reasons only.
            }
        }
    }
    Err(EvalError::user_error(
        "no matching clause for the given arguments".to_string(),
        ctx.call_span.clone(),
    )
    .into())
}

/// Validate function arguments, build a call-frame EvalFrame, and return it.
///
/// Handles arity validation, default params, variadic params, and system-injected
/// named args. The returned EvalFrame carries the bound params and closure captures
/// for use with `Thunk::core_expr` and `EvalFrame`-based variable lookup.
pub(crate) async fn bind_args_thunks(
    params: &[Param],
    positional: &[Arc<Thunk>],
    named: Option<&IndexMap<String, Arc<Thunk>>>,
    closure_env: Arc<Vec<Arc<Thunk>>>,
    ctx: &Arc<EvalContext>,
    call_span: &Span,
) -> EvalResult<Arc<EvalFrame>> {
    // BIND-SPLIT: Classify params using resolved_type and variadic flag.
    // Typed variadics have variadic=true and a concrete resolved_type (not Unknown/None).
    // Untyped rest has variadic=true and resolved_type=None (or Unknown).
    // Fixed params have variadic=false.
    let mut regular_params: Vec<&Param> = Vec::new();
    let mut typed_variadic_params: Vec<&Param> = Vec::new();
    let mut rest_param: Option<&Param> = None;
    for p in params.iter() {
        if p.variadic {
            match &p.resolved_type {
                // Typed variadic: has a concrete TypeValue (not Unknown) → typed bucket
                Some(tv) if !is_typevalue_unknown(tv) => {
                    typed_variadic_params.push(p);
                }
                // Unknown or None: untyped rest bucket
                _ => rest_param = Some(p),
            }
        } else {
            regular_params.push(p);
        }
    }
    let max_positional = regular_params.len();
    let has_any_variadic = !typed_variadic_params.is_empty() || rest_param.is_some();

    // BIND-ARITY: Per-parameter coverage check (Kotlin model)
    // Each required parameter must be reachable via positional index OR named argument
    let mut required_count = 0;
    for (i, param) in regular_params.iter().enumerate() {
        let is_required = get_default(param).is_none();
        if is_required {
            required_count += 1;
            let covered_positionally = i < positional.len();
            let covered_by_name = named.map(|n| n.contains_key(&param.name)).unwrap_or(false);
            if !covered_positionally && !covered_by_name {
                return Err(EvalError::missing_required_param(
                    param.name.clone(),
                    call_span.clone(),
                )
                .into());
            }
        }
    }

    // Without any variadic: positional args must not exceed max_positional
    if !has_any_variadic && positional.len() > max_positional {
        // Use Range when there are optional params, Exact when all params are required
        let expected = if required_count < max_positional {
            ArityBound::Range(required_count, max_positional)
        } else {
            ArityBound::Exact(max_positional)
        };
        let param_names: Vec<String> = regular_params.iter().map(|p| p.name.clone()).collect();
        let mut err =
            EvalError::arity_mismatch_bound(expected, positional.len(), call_span.clone());
        err.set_arity_params(param_names);
        return Err(err.into());
    }

    // BIND-NAMED-VALIDATE: Check named args against params before filling slots.
    //
    // BIND-SYSTEM: System-injected named args (names containing '∷') are excluded from
    // all user-visible named-arg validation. The '∷' separator is a Unicode character
    // that cannot appear in parser-produced identifiers, so these names can only
    // originate from Rust runtime code (e.g. the @Expr macro implicit-arg injection).
    // This makes the binding unconditional and invisible to tinct code.
    if let Some(named_args) = named {
        for (name, _thunk_id) in named_args {
            // Skip system-injected args (contain '∷').
            if name.contains('∷') {
                continue;
            }
            // C-NO-OVERLAP and C-NAMED-VALID in one position() call
            match regular_params.iter().position(|p| &p.name == name) {
                Some(idx) if idx < positional.len() => {
                    // C-NO-OVERLAP: named arg targets a positionally-bound parameter
                    return Err(Box::new(EvalError::named_arg_conflict(
                        name.clone(),
                        call_span.clone(),
                    )));
                }
                Some(_) => {
                    // Valid: named arg targets an existing param that wasn't positionally bound.
                }
                None => {
                    if has_any_variadic {
                        // Unmatched named arg goes into the rest bucket (see BIND-VARIADIC below).
                    } else {
                        // No variadic param: raise E022
                        let valid_params: Vec<String> =
                            regular_params.iter().map(|p| p.name.clone()).collect();
                        return Err(Box::new(EvalError::unknown_named_arg(
                            name.clone(),
                            valid_params,
                            call_span.clone(),
                        )));
                    }
                }
            }
        }
    }

    // Build param slots as a Vec<Arc<Thunk>> indexed by param.slot.
    // EvalFrame::for_function_call(closure_env, params) creates a frame where
    // VarAddr::Parameter(i) resolves params[i].
    let slot_count = params.len();
    let mut param_slots: Vec<Option<Arc<Thunk>>> = vec![None; slot_count];

    // BIND-POSITIONAL + BIND-NAMED: Fill each regular param slot.
    // Use p.slot (the resolver-assigned parameter index) so that slots are filled at the
    // exact position the resolver reserved for each param.
    //
    // For defaults (SurfaceNode), lower to CoreExpr via lower::lower and wrap as a
    // Thunk::core_expr for lazy evaluation with an empty frame at force time.
    for (i, param) in regular_params.iter().enumerate() {
        let slot = param.slot as usize;
        if i < positional.len() {
            // Positional arg: use Arc<Thunk> directly.
            param_slots[slot] = Some(Arc::clone(&positional[i]));
        } else if let Some(named_args) = named {
            if let Some(named_thunk) = named_args.get(&param.name) {
                // Named arg: use Arc<Thunk> directly.
                param_slots[slot] = Some(Arc::clone(named_thunk));
            } else if let Some(default_node) = get_default(param) {
                // Default param: lower and wrap as a CoreExpr thunk with empty frame.
                let (lowered_default, lower_diags) = crate::lower::lower(
                    &default_node,
                    ctx.scope_frames.as_ref().map(|v| v.as_slice()),
                );
                {
                    let (info_diags, other_diags): (Vec<_>, Vec<_>) = lower_diags
                        .into_iter()
                        .partition(|d| d.level == crate::error::DiagnosticLevel::Info);
                    for d in info_diags {
                        ctx.runtime_diagnostics
                            .lock()
                            .expect("runtime_diagnostics mutex poisoned")
                            .push(d);
                    }
                    if let Some(err) =
                        crate::eval_materialize::lower_errors_to_eval_error(other_diags)
                    {
                        return Err(err);
                    }
                }
                let default_thunk = Arc::new(Thunk::core_expr(
                    Arc::new(lowered_default),
                    EvalFrame::empty(),
                    Arc::clone(ctx),
                    call_span.clone(),
                ));
                param_slots[slot] = Some(default_thunk);
            }
            // else: required param with no coverage — already caught by arity check.
        } else if let Some(default_node) = get_default(param) {
            // Default param (no named args provided).
            let (lowered_default, lower_diags) = crate::lower::lower(
                &default_node,
                ctx.scope_frames.as_ref().map(|v| v.as_slice()),
            );
            {
                let (info_diags, other_diags): (Vec<_>, Vec<_>) = lower_diags
                    .into_iter()
                    .partition(|d| d.level == crate::error::DiagnosticLevel::Info);
                for d in info_diags {
                    ctx.runtime_diagnostics
                        .lock()
                        .expect("runtime_diagnostics mutex poisoned")
                        .push(d);
                }
                if let Some(err) = crate::eval_materialize::lower_errors_to_eval_error(other_diags)
                {
                    return Err(err);
                }
            }
            let default_thunk = Arc::new(Thunk::core_expr(
                Arc::new(lowered_default),
                EvalFrame::empty(),
                Arc::clone(ctx),
                call_span.clone(),
            ));
            param_slots[slot] = Some(default_thunk);
        }
        // else: required param with no arg — already caught by arity check.
    }

    // BIND-VARIADIC: Route excess positional args and unmatched named args into buckets.
    //
    // When there are typed variadic params (`...xs@String ...ns@Int ...rest`):
    //   - Each excess positional arg is materialized to inspect its runtime type.
    //   - It is placed in the first typed bucket whose type it matches (declaration order).
    //   - If no typed bucket matches, it falls into the untyped rest bucket.
    //   - If there is no rest bucket and no typed bucket matches, raise an arity error.
    //   Materializing here is a necessary strictness point: the type of the value determines
    //   which bucket it routes into. Analogous to TypeAssert, which also forces evaluation
    //   at the annotation site.
    //
    // When there are no typed buckets (unannotated `...args` only), no materialization
    // occurs: all excess positionals and unmatched named args flow into rest Dict as-is.
    // Materialization is only necessary to inspect the value's runtime type for bucket dispatch.
    //
    // Named args always go into the rest bucket (keyed by their string name). They are not
    // type-discriminated into typed buckets because their names carry caller intent.
    //
    // Typed buckets are collected into auto-indexed Value::Dict entries (integer keys 0, 1, 2, ...).
    // The rest bucket is a Value::Dict with integer keys for positional args and string keys for named args.
    if has_any_variadic {
        let extra_positionals = &positional[max_positional.min(positional.len())..];

        // Collect typed bucket TypeValues for dispatch.
        // Use p.resolved_type (set by the type checker) rather than re-parsing the annotation.
        // Empty when there are no typed variadics (single unannotated rest case).
        let bucket_types: Vec<Arc<Value>> = typed_variadic_params
            .iter()
            .map(|p| {
                p.resolved_type
                    .clone()
                    .unwrap_or_else(crate::value::unknown_type_val)
            })
            .collect();

        // Accumulate Arc<Thunk> for each typed bucket (in declaration order).
        let mut typed_buckets: Vec<Vec<Arc<Thunk>>> = vec![Vec::new(); typed_variadic_params.len()];
        // Accumulate rest bucket: integer-keyed positionals + string-keyed named.
        let mut rest_dict: IndexMap<HashableValue, Arc<Thunk>> = IndexMap::new();
        let mut rest_int_key: i64 = 0;

        // BIND-VARIADIC: Route each excess positional arg to its bucket.
        //
        // Materialization is only needed when there are typed buckets to route into.
        // When bucket_types is empty (unannotated rest-only case), args flow directly
        // into rest_dict without forcing — preserving lazy evaluation.
        for arg_thunk in extra_positionals.iter() {
            let mut routed = false;

            if !bucket_types.is_empty() {
                // Materialize to inspect the runtime type for bucket dispatch.
                let value = materialize(arg_thunk, Some(call_span), ctx).await?;

                // Try each typed bucket in declaration order — first match wins.
                for (bucket_idx, bucket_ty) in bucket_types.iter().enumerate() {
                    if value_matches_type(&value, bucket_ty, ctx) {
                        typed_buckets[bucket_idx].push(Arc::clone(arg_thunk));
                        routed = true;
                        break;
                    }
                }
            }

            if !routed {
                if rest_param.is_some() {
                    rest_dict.insert(HashableValue::Int(rest_int_key), Arc::clone(arg_thunk));
                    rest_int_key += 1;
                } else {
                    // No rest bucket and no typed bucket matched: arg cannot be accepted.
                    let expected = ArityBound::Exact(max_positional);
                    return Err(EvalError::arity_mismatch_bound(
                        expected,
                        positional.len(),
                        call_span.clone(),
                    )
                    .into());
                }
            }
        }

        // Route unmatched named args into the rest bucket (not type-discriminated).
        if let Some(named_args) = named {
            for (name, named_thunk) in named_args {
                if name.contains('∷') {
                    continue;
                }
                if regular_params.iter().any(|p| &p.name == name) {
                    continue;
                }
                rest_dict.insert(
                    HashableValue::Str(Arc::from(name.as_str())),
                    Arc::clone(named_thunk),
                );
            }
        }

        // BIND-RESULT: Bind each typed variadic bucket as an auto-indexed Dict.
        // Use p.slot (resolver-assigned) for each typed variadic param.
        for (bucket_args, p) in typed_buckets.into_iter().zip(typed_variadic_params.iter()) {
            let slot = p.slot as usize;
            let mut dict = IndexMap::new();
            for (i, thunk) in bucket_args.into_iter().enumerate() {
                dict.insert(crate::value::HashableValue::Int(i as i64), thunk);
            }
            param_slots[slot] = Some(Arc::new(Thunk::value(
                Value::Dict {
                    entries: dict,
                    type_val: crate::value::unknown_type_val(),
                },
                call_span.clone(),
            )));
        }

        // BIND-RESULT: Bind the untyped rest bucket as a Dict (if present).
        // Use rest_param.slot (resolver-assigned) directly.
        if let Some(rp) = rest_param {
            let rest_slot = rp.slot as usize;
            let rest_thunk = Arc::new(Thunk::value(
                Value::Dict {
                    entries: rest_dict,
                    type_val: crate::value::unknown_type_val(),
                },
                call_span.clone(),
            ));
            param_slots[rest_slot] = Some(rest_thunk);
        }
    }

    // Collect param_slots into a Vec<Arc<Thunk>>.
    // Invariant: all slots must be filled after arity checks above. An unfilled slot
    // indicates a bug in the arity checking or slot-filling logic above.
    let params_vec: Vec<Arc<Thunk>> = param_slots
        .into_iter()
        .map(|opt| opt.expect("param slot invariant violated: unfilled slot after arity check"))
        .collect();

    Ok(EvalFrame::for_function_call(closure_env, params_vec))
}

/// Extract the default value node from a param's annotation, if present.
///
/// `default:` is specified via PropertyDict annotation with a "default" key, e.g.:
/// `[fn [let x@[default: 42]] ...]`
///
/// Returns the `Arc<SurfaceNode>` of the default expression directly.
/// The caller lowers this to CoreExpr via `lower::lower` and wraps the result in a
/// `Thunk::core_expr` for lazy evaluation in the default scope.
pub(crate) fn get_default(param: &Param) -> Option<Arc<SurfaceNode>> {
    param
        .annotation
        .as_ref()
        .and_then(|ann| ann.node.get_property(DEFAULT_ANNOTATION_KEY))
        .map(Arc::clone)
}

